#!/usr/bin/env node
// Reads the VS Code theme JSON files from local clones of the theme repos and
// writes content/themes.generated.ts. Run it after a theme repo changes:
//
//   THEME_REPOS_DIR=/path/to/clones npm run palettes
//
// THEME_REPOS_DIR must contain genshin-hsr-themes, wuwa-themes,
// columbina-theme and cupcake-maroon side by side.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const reposDir = process.env.THEME_REPOS_DIR ?? join(root, "..");

const PACKS = [
  { id: "hoyoverse", repo: "genshin-hsr-themes" },
  { id: "wuwa", repo: "wuwa-themes" },
  { id: "columbina", repo: "columbina-theme" },
  { id: "cupcake-maroon", repo: "cupcake-maroon" },
];

// Token roles shown in the mini editor, each with the TextMate scopes that
// usually carry it, most specific first.
const ROLES = {
  keyword: ["keyword.control", "keyword", "storage.type", "storage"],
  string: ["string.quoted", "string"],
  fn: ["entity.name.function", "support.function", "meta.function-call"],
  type: ["entity.name.type", "entity.name.class", "support.class", "support.type"],
  number: ["constant.numeric", "constant"],
  comment: ["comment"],
  variable: ["variable.other", "variable"],
};

// VS Code theme files are JSONC: strip comments and trailing commas.
function readJsonc(path) {
  const text = readFileSync(path, "utf8");
  let out = "";
  let inString = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inString) {
      out += ch;
      if (ch === "\\") out += text[++i] ?? "";
      else if (ch === '"') inString = false;
    } else if (ch === '"') {
      inString = true;
      out += ch;
    } else if (ch === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      out += "\n";
    } else if (ch === "/" && text[i + 1] === "*") {
      i += 2;
      while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) i++;
      i++;
    } else out += ch;
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

// "#rgb", "#rrggbb" or "#rrggbbaa" → "#rrggbb" (alpha dropped for swatches).
function hex(value) {
  if (typeof value !== "string" || !value.startsWith("#")) return undefined;
  const v = value.slice(1);
  if (v.length === 3 || v.length === 4) return "#" + [...v.slice(0, 3)].map((c) => c + c).join("").toUpperCase();
  if (v.length === 6 || v.length === 8) return "#" + v.slice(0, 6).toUpperCase();
  return undefined;
}

function tokenColor(tokenColors, scopes) {
  for (const wanted of scopes) {
    for (const rule of tokenColors ?? []) {
      const ruleScopes = Array.isArray(rule.scope)
        ? rule.scope
        : String(rule.scope ?? "").split(",").map((s) => s.trim());
      if (ruleScopes.some((s) => s === wanted || s.startsWith(wanted + ".")) && hex(rule.settings?.foreground)) {
        return hex(rule.settings.foreground);
      }
    }
  }
  return undefined;
}

function variant(uiTheme) {
  if (uiTheme === "hc-black" || uiTheme === "hc-light") return "high-contrast";
  return uiTheme === "vs-dark" ? "dark" : "light";
}

const packs = [];
for (const { id, repo } of PACKS) {
  const dir = join(reposDir, repo);
  if (!existsSync(join(dir, "package.json"))) {
    console.error(`Missing ${dir}. Set THEME_REPOS_DIR to the folder holding the theme repos.`);
    process.exit(1);
  }
  const pkg = readJsonc(join(dir, "package.json"));
  const themes = pkg.contributes.themes.map((t) => {
    const json = readJsonc(join(dir, t.path));
    const c = json.colors ?? {};
    const bg = hex(c["editor.background"]) ?? (variant(t.uiTheme) === "light" ? "#FFFFFF" : "#1E1E1E");
    const fg = hex(c["editor.foreground"]) ?? hex(c.foreground) ?? (variant(t.uiTheme) === "light" ? "#333333" : "#D4D4D4");
    const roles = {};
    for (const [role, scopes] of Object.entries(ROLES)) roles[role] = tokenColor(json.tokenColors, scopes) ?? fg;
    return {
      label: t.label,
      variant: variant(t.uiTheme),
      bg,
      fg,
      accent: hex(c["activityBar.background"]) ?? hex(c["button.background"]) ?? roles.keyword,
      ...roles,
    };
  });
  packs.push({ id, version: pkg.version, themes });
  console.log(`${repo}: ${themes.length} themes`);
}

const banner = `// Generated by scripts/extract-theme-palettes.mjs — do not edit by hand.\n// Run \`npm run palettes\` to refresh.\n\n`;
const body = `import type { ThemePalette } from "./types";\n\nexport const themePalettes: Record<string, { version: string; themes: ThemePalette[] }> = ${JSON.stringify(
  Object.fromEntries(packs.map((p) => [p.id, { version: p.version, themes: p.themes }])),
  null,
  2,
)};\n`;
writeFileSync(join(root, "content", "themes.generated.ts"), banner + body);
console.log("Wrote content/themes.generated.ts");
